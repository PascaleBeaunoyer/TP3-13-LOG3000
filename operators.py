def add(a,b):
    """Rôle: retourne la somme de deux nombres.
       Entrées: a, b (float ou int)
       Sortie: somme de a et b (float ou int)"""
    return a + b

def subtract(a,b):
    """Rôle: retourne la différence de deux nombres.
       Entrées: a, b (float ou int)
       Sortie: différence de a et b (float ou int)"""
    return a - b

def multiply(a,b):
    """Rôle: retourne le produit de deux nombres.
       Entrées: a, b (float ou int)
       Sortie: produit de a et b (float ou int)"""
    return a * b

def divide(a,b):
    """Rôle: retourne le quotient de deux nombres.
       Entrées: a, b (float ou int)
       Sortie: quotient de a et b (float ou int)"""
    return a / b
